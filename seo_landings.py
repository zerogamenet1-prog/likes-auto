SLUGS = tuple(PAGES.keys())


def page_for(slug):
    return PAGES.get((slug or "").strip().lower())


def cat_to_slug(name):
    n = (name or "").strip().lower()
    if not n:
        return ""
    compact = n.replace(" ", "")
    if compact in {"x", "twitter", "twitter/x", "x/twitter"} or n.startswith("twitter"):
        return "twitter"
    for slug, meta in PAGES.items():
        for needle in meta["needles"]:
            if needle in n:
                return slug
    return ""


def plat_href(name, fallback="/services"):
    slug = cat_to_slug(name)
    return "/%s" % slug if slug else fallback


def match_shop_name(slug, platforms):
    meta = page_for(slug)
    if not meta:
        return ""
    needles = tuple(x.lower() for x in meta["needles"])
    for row in platforms or []:
        n = (row.get("name") or "").strip()
        low = n.lower()
        if slug == "twitter" and (low in {"x", "twitter", "twitter / x"} or "twitter" in low or low == "x"):
            return n
        if any(k in low for k in needles):
            return n
    return ""
