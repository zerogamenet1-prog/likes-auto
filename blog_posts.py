def _im(*rows):
    return list(rows)


def _build(spec):
    know = [know_funnel(), know_budget(), know_safe(), know_content()]
    intro = [spec["hook"], know_proof(), know_algo()]
    intro.append(spec.get("extra") or know_content())
    secs = []
    more = spec.get("more") or []
    for i, title in enumerate(spec["heads"]):
        paras = [spec["tips"][i], know[i % 4]]
        if i < len(more):
            paras.append(more[i])
        secs.append((title, paras, spec["bullets"][i]))
    outro = [
        spec["end"],
        "ทดลองจำนวนน้อยได้ที่%s หลัง%s เติม%s ได้ทันที และอ่าน%s ถ้ายังไม่เคยใช้แผง" % (SVC, SIGN, PAY, HOW),
    ]
    return {
        "slug": spec["slug"],
        "title": spec["title"],
        "tags": spec["tags"],
        "queue": spec.get("queue", 0),
        "ago": spec.get("ago", 0),
        "body": story(spec["imgs"], intro, secs, outro),
    }


